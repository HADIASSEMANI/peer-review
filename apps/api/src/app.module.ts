import { Module } from '@nestjs/common';
import { ConfigModule } from '@nestjs/config';
import { APP_GUARD, APP_PIPE } from '@nestjs/core';
import { ZodValidationPipe } from 'nestjs-zod';
import { AuthModule } from './auth/auth.module';
import { JwtAuthGuard } from './auth/jwt-auth.guard';
import { RolesGuard } from './common/roles.guard';
import { CoursesModule } from './courses/courses.module';
import { EvaluationsModule } from './evaluations/evaluations.module';
import { HealthModule } from './health/health.module';
import { PrismaModule } from './prisma/prisma.module';
import { TeamsModule } from './teams/teams.module';
import { UsersModule } from './users/users.module';

@Module({
  imports: [
    ConfigModule.forRoot({
      isGlobal: true,
      // Order matters. packages/db/.env is generated by build-schema.mjs and
      // holds the RESOLVED DATABASE_URL (absolute for SQLite), so it must win
      // over the human-authored relative value in the repo-root .env.
      // Everything else — JWT_SECRET, ports — comes from the root file.
      envFilePath: ['../../packages/db/.env', '.env', '../../.env'],
    }),
    PrismaModule,
    AuthModule,
    UsersModule,
    CoursesModule,
    TeamsModule,
    EvaluationsModule,
    HealthModule,
  ],
  providers: [
    // Everything is authenticated unless a route is marked @Public().
    { provide: APP_GUARD, useClass: JwtAuthGuard },
    { provide: APP_GUARD, useClass: RolesGuard },
    // Validates every DTO built with createZodDto against its shared schema.
    { provide: APP_PIPE, useClass: ZodValidationPipe },
  ],
})
export class AppModule {}
